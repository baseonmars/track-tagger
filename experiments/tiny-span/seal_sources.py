"""Rescreen acquired text packages together and seal a source-only blind inventory."""
import argparse
from collections import Counter
from hashlib import sha256
import json
from pathlib import Path
import re
import sys

from blind_sources import write_jsonl
from inventory import STUDY_COMMIT, digest, indexed, load, require, verify_study


def fixed_source_transfer_template(text):
    """Recognize the repeated auto-info scaffold identified in the blind source audit."""
    lines = [line.strip() for line in text.split("\n")]
    if (
        len(lines) < 10
        or any(lines[index] for index in (0, 5, 8))
        or not lines[1]
        or not (lines[3] or lines[4])
        or not lines[6].startswith("Source:")
        or not lines[7].startswith("Transfer:")
    ):
        return False
    first_track = next((line for line in lines[9:] if line), "")
    return re.match(r"0?1[.)] \S", first_track) is not None



def checksum_only_template(text):
    """Identify packages with only generated audio checksums across all notes."""
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    payload = [
        line for line in lines
        if not re.match(r";\s*flac fingerprints generated by xact\b", line, re.I)
    ]
    if not payload:
        return None
    if all(re.fullmatch(r".+\.flac\s*:\s*[\da-f]{32}", line, re.I) for line in payload):
        return "flac-fingerprint-only"
    if all(re.fullmatch(r"[\da-f]{32}\s+\*?.+\.(flac|shn|wav|mp3)", line, re.I) for line in payload):
        return "md5-fingerprint-only"
    return None


def seal(cache, study, destination, passes, priority, target, package_index=None):
    require(not destination.is_relative_to(Path(__file__).resolve().parents[2]), "keep text outside the repository")
    verify_study(study)
    sys.path.insert(0, str(study))
    from experiments.parser.acquire import decode_note, select_files
    from experiments.parser.study_v2.components import groups, keys
    from experiments.parser.study_v2.corpus import aliases, uploader
    from experiments.parser.study_v2.labels import source_hash

    records = {}
    accepted_inputs = {}
    prior_ids = set()
    package_sources = []
    original_index = load(package_index) if package_index else None
    roots = [cache, cache / "v2", *passes]
    if original_index is not None:
        require(set(original_index) == {root.name for root in roots}, "package replay roots differ")
    for root in roots:
        old = root in (cache, cache / "v2")
        package_root = root / "packages"
        if original_index is not None:
            entries = original_index[root.name]
        else:
            entries = [
                {"id": directory.name}
                for directory in sorted(package_root.glob("*"))
                if directory.is_dir()
            ]
        package_sources.append((root.name, entries))
        for entry in entries:
            identifier = entry["id"]
            require(Path(identifier).name == identifier and identifier not in (".", ".."), "unsafe package id")
            directory = package_root / identifier
            if old:
                prior_ids.add(identifier)
            path = directory / "package.json"
            present = path.is_file()
            if original_index is not None and not entry.get("package_sha256"):
                continue
            if original_index is not None:
                require(present, "frozen package is missing")
            if not present:
                continue
            package_bytes = path.read_bytes()
            package_hash = sha256(package_bytes).hexdigest()
            if original_index is not None:
                require(entry["package_sha256"] == package_hash, "package replay digest changed")
            entry["package_sha256"] = package_hash
            package = json.loads(package_bytes)
            require(package["package_id"] == identifier, "package identifier differs")
            if not package["complete"] or not package["notes"] or not package["audio_files"]:
                continue
            if not old:
                metadata = (directory / "archive-metadata.json").read_bytes()
                require(sha256(metadata).hexdigest() == package["archive_metadata_sha256"], "package metadata digest changed")
                expected_notes, expected_files = select_files(json.loads(metadata))
                require(
                    [note["path"] for note in package["notes"]] == [note["name"] for note in expected_notes]
                    and [audio["path"] for audio in package["audio_files"]] == [audio["name"] for audio in expected_files],
                    "original package inventory differs",
                )
            notes = []
            for note in package["notes"]:
                data = (directory / note["local_path"]).read_bytes()
                require(sha256(data).hexdigest() == note["sha256"], "cached note digest mismatch")
                text, _ = decode_note(data)
                notes.append({"name": note["path"], "text": text.replace("\r\n", "\n").replace("\r", "\n")})
            member = f"{root.name}/{identifier}" if old else identifier
            old_record = records.get(member)
            text = "\n".join(note["text"] for note in notes)
            files = [entry["path"] for entry in package["audio_files"]]
            case = {"id": identifier, "notes": notes, "files": files}
            if old_record is not None:
                require(
                    case == accepted_inputs[member] and keys(package, text) == keys(*old_record),
                    "candidate package changed between discovery passes",
                )
                continue
            records[member] = package, text
            if not old:
                accepted_inputs[identifier] = case

    exclusions = load(cache / "v2/source-audit-exclusions.json")
    prior_ids.update(exclusions["excluded_ids"])
    prior_ids.update(indexed(cache / "v2/selected-acquisition-manifest.jsonl", "package_id"))
    prior_ids.update(indexed(cache / "v2/neighbor-currentpool-input-manifest.jsonl", "package_id"))
    manual_edges = [(f"v2/{left}", f"v2/{right}") for left, right in exclusions["manual_edges"]]
    template_members = sorted(
        member for member, (_, text) in records.items() if fixed_source_transfer_template(text)
    )
    templates = {"fixed_source_transfer_template": template_members}
    for member, (_, text) in sorted(records.items()):
        family = checksum_only_template(text)
        if family is not None:
            templates.setdefault(family, []).append(member)
    for members in templates.values():
        if members:
            manual_edges.extend((members[0], member) for member in members[1:])
    components = groups(records, manual_edges)
    exposed = {
        component
        for member, component in components.items()
        if member not in accepted_inputs or member in prior_ids
    }
    prioritize = {}
    for packet in priority:
        for identifier, case in indexed(packet).items():
            require(identifier in accepted_inputs, "early review package is missing")
            require(
                source_hash(case) == source_hash(accepted_inputs[identifier]),
                "early review source bytes changed",
            )
            prioritize.setdefault(identifier, len(prioritize))

    selected = []
    found = set()
    artists = Counter()
    dispositions = Counter()
    order = sorted(accepted_inputs, key=lambda identifier: (
        prioritize.get(identifier, len(prioritize)),
        sha256(("tiny-span-blind-v1:" + identifier).encode()).hexdigest(),
    ))
    for identifier in order:
        component = components[identifier]
        package, _ = records[identifier]
        names = aliases(package["artist"])
        if identifier in prior_ids:
            dispositions["prior_identifier"] += 1
        elif component in exposed:
            dispositions["related_to_prior_component"] += 1
        elif not uploader(package):
            dispositions["missing_uploader"] += 1
        elif component in found:
            dispositions["already_represented_component"] += 1
        elif any(artists[name] >= 5 for name in names):
            dispositions["artist_alias_cap"] += 1
        elif len(selected) >= target:
            dispositions["over_target"] += 1
        else:
            found.add(component)
            artists.update(names)
            selected.append(accepted_inputs[identifier] | {"group": component, "split": "blind_test"})

    destination.mkdir(parents=True, exist_ok=False)
    write_jsonl(destination / "blind-inputs.jsonl", selected)
    write_jsonl(destination / "blind-manifest.jsonl", (
        {"id": case["id"], "group": case["group"], "source_input_sha256": source_hash(case)}
        for case in selected
    ))
    index_path = destination / "package-index.json"
    index_path.write_text(json.dumps(dict(package_sources), sort_keys=True) + "\n")
    result = {
        "package_index_sha256": digest(index_path),
        "priority_packet_sha256": [digest(packet) for packet in priority],
        "source_grouping_revision": STUDY_COMMIT,
        "additional_source_templates": {
            family: {
                "prior_members": sum(member not in accepted_inputs for member in members),
                "new_members": sum(member in accepted_inputs for member in members),
                "source_components": len({components[member] for member in members}),
            }
            for family, members in templates.items()
        },
        "prior_cached_records": len(records) - len(accepted_inputs),
        "acquired_unique_packages": len(accepted_inputs),
        "excluded_packages": dict(dispositions),
        "selected_source_components": len(found),
        "selected_early_review_sources": sum(case["id"] in prioritize for case in selected),
        "early_review_sources_supplied": len(prioritize),
        "largest_selected_artist_alias": max(artists.values(), default=0),
        "target": target,
        "blind_inputs_sha256": digest(destination / "blind-inputs.jsonl"),
        "blind_manifest_sha256": digest(destination / "blind-manifest.jsonl"),
    }
    (destination / "blind-freeze.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for argument in ("cache", "study", "destination"):
        parser.add_argument(argument, type=lambda value: Path(value).resolve())
    parser.add_argument("passes", nargs="+", type=lambda value: Path(value).resolve())
    parser.add_argument("--package-index", type=Path)
    parser.add_argument("--priority", action="append", type=Path, default=[])
    parser.add_argument("--target", type=int, default=200)
    seal(**vars(parser.parse_args()))
